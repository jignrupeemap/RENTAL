<?php
declare(strict_types=1);

namespace App\Services\Deploy;

/**
 * Builds database/install.sql: every migration in order plus the
 * schema_migrations rows that mark them applied, as ONE file for
 * phpMyAdmin → Import (spec 44 "Database import SQL"). After importing it,
 * bin/migrate.php and /setup report "up to date", and later migrations
 * apply on top as usual.
 *
 * The file is generated, never edited by hand: php bin/build-install-sql.php
 */
final class InstallSql
{
    public static function build(string $migrationsDir): string
    {
        $files = glob(rtrim($migrationsDir, '/') . '/*.sql') ?: [];
        sort($files, SORT_STRING);

        $out = "-- Rental, PG & Lease marketplace: complete database for a NEW installation.\n"
            . "-- Import into an EMPTY database (hPanel → Databases → phpMyAdmin → Import).\n"
            . "-- Contains the schema and reference data only: no users, no properties.\n"
            . "-- Generated by bin/build-install-sql.php from database/migrations/ - do not edit.\n"
            . '-- Migrations included: ' . count($files) . "\n\n"
            . "SET NAMES utf8mb4;\n"
            . "SET time_zone = '+00:00';\n"
            . "SET SQL_MODE = 'STRICT_TRANS_TABLES,NO_ZERO_DATE,NO_ZERO_IN_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION';\n\n";

        $marks = [];
        foreach ($files as $file) {
            $version = basename($file, '.sql');
            $sql = (string) file_get_contents($file);
            $out .= "-- ================================================================\n-- {$version}\n-- ================================================================\n"
                . rtrim($sql) . "\n\n";
            $marks[] = sprintf("('%s', '%s')", $version, hash('sha256', $sql));
        }

        // Same table bin/migrate.php creates; the rows tell it these are done.
        $out .= "-- ================================================================\n-- Mark the migrations above as applied\n-- ================================================================\n"
            . "CREATE TABLE IF NOT EXISTS schema_migrations (\n"
            . "    version     VARCHAR(100) NOT NULL PRIMARY KEY,\n"
            . "    checksum    CHAR(64) NOT NULL,\n"
            . "    applied_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP\n"
            . ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n"
            . "INSERT INTO schema_migrations (version, checksum) VALUES\n" . implode(",\n", $marks) . ";\n";
        return $out;
    }
}
